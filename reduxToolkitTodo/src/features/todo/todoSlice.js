import {createSlice , nanoid} from '@reduxjs/toolkit'


//nanoid is used to generate unique ids for each todo item

const initialState ={
    todos:[
        {
            id :1 , 
            text:"Hello world"
        }
    ]
}

export const todoSlice = createSlice({
    name :'todo',
    initialState,
    //ye same format hona chahiye

    reducers:{ //reducers are the properties, it will consist of properties or functions that will be used to update the state
    addTodo: (state , action) => {
        const todo = {
            id: nanoid(),
            text: action.payload
            //payload ek object hai jo action se data lega
        }
        state.todos.push(todo)
    },
    //ye syntax same rahega always have accesss to (statecurrent state  , action(jo data pass ho raha hai))
    removeTodo: (state , action) => {
        // ab remove karne ke liye action mai kuch id bheji hogi to direct filter laga dete hai
        state.todos= state.todos.filter((todo) => todo.id !== action.payload)

        // filter se jo match nhi kar raha wo gayab ho jayega
    }
    
    //context api mai hum sirf declaration likh rahe the lekin redu mai hum puri defination likhenge naki sirf declaration 
        
    }
})



// jitni bhi functionality hai unn sablko export kyumki ye individually kaam mai ayegi in components

export const {addTodo , removeTodo} = 
todoSlice.actions

// ab store ko sab reducers ki list chahiye hoti hai 

export default todoSlice.reducer





